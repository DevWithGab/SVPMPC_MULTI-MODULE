import test from 'node:test';
import assert from 'node:assert/strict';
import React, { act } from 'react';
import { createRoot } from 'react-dom/client';
import { createServer } from 'vite';

test('scanner dashboard follows scheduled boundaries and refreshes availability and closures without reloading', async () => {
  const vite = await createServer({ server: { middlewareMode: true, hmr: false }, appType: 'custom' });
  const container = document.createElement('div');
  document.body.append(container);
  const root = createRoot(container);
  const saved = { now: Date.now, interval: globalThis.setInterval, clear: globalThis.clearInterval, act: globalThis.IS_REACT_ACT_ENVIRONMENT, visibility: Object.getOwnPropertyDescriptor(document, 'visibilityState') };
  let api, getEvents;
  try {
    const { default: Dashboard } = await vite.ssrLoadModule('/src/components/attendance/scanner_operator/Dashboard.jsx');
    ({ eventAPI: api } = await vite.ssrLoadModule('/src/services/api.js'));
    getEvents = api.getEvents;
    let now = Date.parse('2026-10-21T13:14:59+08:00');
    Date.now = () => now;
    const timers = new Map();
    globalThis.setInterval = (callback, delay) => { timers.set(delay, callback); return delay; };
    globalThis.clearInterval = delay => timers.delete(delay);
    globalThis.IS_REACT_ACT_ENVIRONMENT = true;
    let visible = true;
    Object.defineProperty(document, 'visibilityState', { configurable: true, get: () => visible ? 'visible' : 'hidden' });
    let event = { eventId: 'TEST', eventName: 'Afternoon assembly', eventDate: '2026-10-21', startTime: '13:15', endTime: '14:25', status: 'upcoming' };
    let fail = false;
    const pages = [];
    api.getEvents = async ({ page }) => {
      pages.push(page);
      if (fail && page === 2) throw new Error('Synthetic request failure');
      return { events: page === 1 ? [{ ...event, eventId: 'PENDING', status: 'pending_approval' }] : [event], pagination: { totalPages: 2 } };
    };
    let destination;
    await act(async () => root.render(React.createElement(Dashboard, { setActiveTab: tab => { destination = tab; } })));
    const button = () => container.querySelector('header button');
    assert.equal(button().disabled, true);
    assert.ok(pages.includes(2));
    assert.match(container.querySelector('[aria-current="step"]').textContent, /Waiting/);
    now = Date.parse('2026-10-21T13:15:00+08:00');
    await act(async () => timers.get(1000)());
    assert.equal(button().disabled, false, 'scheduled start activates upcoming events');
    assert.match(container.querySelector('[aria-current="step"]').textContent, /Scanning open/);
    assert.equal(container.querySelectorAll('.sod-upcoming-list li').length, 0, 'active sessions no longer appear in upcoming');
    assert.equal(container.querySelectorAll('.sod-event-list li').length, 1, 'pending approvals remain excluded');
    await act(async () => button().click());
    assert.equal(destination, 'scanner');
    fail = true;
    await act(async () => timers.get(10000)());
    assert.equal(button().disabled, false, 'failed later pages preserve the complete previous list');
    assert.match(container.textContent, /Retrying automatically/);
    fail = false;
    event = { ...event, status: 'closed' };
    await act(async () => timers.get(10000)());
    assert.equal(button().disabled, true);
    assert.doesNotMatch(container.textContent, /Retrying automatically/);
    event = { ...event, status: 'active' };
    await act(async () => window.dispatchEvent(new window.Event('focus')));
    assert.equal(button().disabled, false);
    visible = false;
    const beforeHidden = pages.length;
    await act(async () => timers.get(10000)());
    assert.equal(pages.length, beforeHidden);
    event = { ...event, status: 'cancelled' };
    visible = true;
    await act(async () => document.dispatchEvent(new window.Event('visibilitychange')));
    assert.equal(button().disabled, true);
    event = { ...event, status: 'active' };
    await act(async () => window.dispatchEvent(new window.Event('online')));
    assert.equal(button().disabled, false);
    now = Date.parse('2026-10-21T14:25:00+08:00');
    await act(async () => timers.get(1000)());
    assert.equal(button().disabled, true, 'stale active status cannot extend scanning past the end');
  } finally {
    await act(async () => root.unmount());
    container.remove();
    if (api) api.getEvents = getEvents;
    Date.now = saved.now;
    globalThis.setInterval = saved.interval;
    globalThis.clearInterval = saved.clear;
    globalThis.IS_REACT_ACT_ENVIRONMENT = saved.act;
    if (saved.visibility) Object.defineProperty(document, 'visibilityState', saved.visibility);
    else delete document.visibilityState;
    await vite.close();
  }
});
